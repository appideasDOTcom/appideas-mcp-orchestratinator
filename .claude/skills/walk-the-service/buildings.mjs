// Settings ▸ Sharing ▸ Buildings in the app (costmo, 2026-11-27): ⊕ adds a row being named, Return saves;
// ✎ renames, Escape puts it back; the checkmark moves the default; the section folds. All by real clicks.
//   node buildings.mjs <port> <label>
import { pane, tab, boardView, SHOTS } from './lib.mjs';
const [port, label] = process.argv.slice(2);
const p = await pane(Number(port));
await tab(p, 'sharing');
const b = await boardView(Number(port), 'buildings');
let fails = 0;
const ok = (c, m, x = '') => { console.log(`  ${c ? '✓' : '✗'} ${m}${c || !x ? '' : `  (${x})`}`); if (!c) fails++; };
const g = await boardView(Number(port), 'general').catch(() => null);
if (g) ok(!(await g.locator('#set-buildings').count()), 'General\'s board view has no Buildings');
await b.locator('#set-buildings [data-set="building-add"]').waitFor({ timeout: 20000 });
ok(!(await b.locator('#building-new').count()), 'no add field until ⊕');
await b.locator('#set-buildings [data-set="building-add"]').click();
await b.locator('#building-new').waitFor();
await b.keyboard.type('Walk Lab');
await b.keyboard.press('Enter');
await b.locator('[data-building-label]', { hasText: 'Walk Lab' }).waitFor({ timeout: 10000 });
ok(true, '⊕, a name, Return: Walk Lab is made');
const lab = await b.locator('[data-building-label]', { hasText: 'Walk Lab' }).getAttribute('data-building-label');
await b.locator(`[data-set="building-edit"][data-id="${lab}"]`).click();
await b.keyboard.type('Nope');
await b.keyboard.press('Escape');
await b.waitForTimeout(400);
ok((await b.locator(`[data-building-label="${lab}"]`).innerText()) === 'Walk Lab', 'Escape puts the name back');
await b.locator(`[data-set="building-edit"][data-id="${lab}"]`).click();
await b.keyboard.type('Walk Workshop');
await b.keyboard.press('Enter');
await b.locator(`[data-building-label="${lab}"]`, { hasText: 'Walk Workshop' }).waitFor({ timeout: 10000 });
ok(true, '✎, a name, Return: renamed');
await b.locator(`[data-set="building-default"][data-id="${lab}"]`).click();
await b.locator(`[data-building-row="${lab}"] .bld-default.on`).waitFor({ timeout: 10000 });
ok(true, 'the checkmark moves the default');
const hq = await b.locator('[data-set="building-default"]').first().getAttribute('data-id');
await b.locator(`[data-set="building-default"][data-id="${hq}"]`).click();
await b.locator(`[data-building-row="${hq}"] .bld-default.on`).waitFor({ timeout: 10000 });
await b.screenshot({ path: `${SHOTS}${label}-b1-buildings.png`, fullPage: true });
await b.locator(`[data-set="building-delete"][data-id="${lab}"]`).click();
await b.locator(`[data-building-row="${lab}"]`).waitFor({ state: 'detached', timeout: 10000 });
ok(true, 'the trash can deletes the empty building');
await b.locator('#set-buildings button.fold').click();
ok(await b.locator('#set-bld-body').isHidden(), 'the section folds');
await b.screenshot({ path: `${SHOTS}${label}-b2-folded.png`, fullPage: true });
await b.locator('#set-buildings button.fold').click();
await p.screenshot({ path: `${SHOTS}${label}-b3-sharing-tab.png`, fullPage: true });
console.log(fails ? `FAIL ${fails}` : 'PASS');
process.exit(fails ? 1 : 0);
